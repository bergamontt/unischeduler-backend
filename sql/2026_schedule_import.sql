-- PostgreSQL schema migration for the optional schedule import endpoint.
-- Run ONCE against a backed-up database, preferably through Flyway/Liquibase.
-- This migration augments existing CourseClass rows; it does not delete them.
BEGIN;

CREATE TABLE IF NOT EXISTS schedule_import_scope (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    speciality_id BIGINT NOT NULL REFERENCES speciality(id),
    study_year INTEGER NOT NULL,
    semester VARCHAR(255) NOT NULL,
    academic_year VARCHAR(9) NOT NULL,
    CONSTRAINT uq_schedule_import_scope UNIQUE
        (speciality_id, study_year, semester, academic_year)
);

ALTER TABLE course_class ADD COLUMN IF NOT EXISTS import_scope_id BIGINT;
ALTER TABLE course_class ADD COLUMN IF NOT EXISTS source_key VARCHAR(64);
ALTER TABLE course_class ADD COLUMN IF NOT EXISTS source_row INTEGER;
ALTER TABLE course_class ADD COLUMN IF NOT EXISTS source_metadata TEXT;
ALTER TABLE course_class ADD COLUMN IF NOT EXISTS description VARCHAR(1000);
ALTER TABLE course_class ADD COLUMN IF NOT EXISTS archived BOOLEAN DEFAULT FALSE;
UPDATE course_class SET archived = FALSE WHERE archived IS NULL;
ALTER TABLE course_class ALTER COLUMN archived SET NOT NULL;

-- Imported entries may legitimately omit these fields in university spreadsheets.
ALTER TABLE course_class ALTER COLUMN teacher DROP NOT NULL;
ALTER TABLE course_class ALTER COLUMN class_group DROP NOT NULL;
ALTER TABLE course_class ALTER COLUMN location DROP NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_import_class_key
    ON course_class(import_scope_id, source_key);

DO $$ BEGIN
    ALTER TABLE course_class ADD CONSTRAINT fk_course_class_import_scope
        FOREIGN KEY (import_scope_id) REFERENCES schedule_import_scope(id);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
COMMIT;
